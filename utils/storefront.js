export const asset = (src) =>
  /^\/gallery\/.+\.jpg$/.test(src || "")
    ? src.replace("/gallery/", "/optimized/gallery/").replace(".jpg", ".webp")
    : /^\/(images|media)\/.+\.(jpg|jpeg|png|webp|avif)$/.test(src || "")
      ? `/optimized/${src
          .split("/")
          .pop()
          .replace(/\.[^.]+$/, ".webp")}`
      : src;
export const categoryOf = (id) =>
  (String(id) === "pine-nut-honey" || [1, 2, 3, 4].includes(Number(id)))
    ? "honey"
    : Number(id) === 8
      ? "craft"
      : ["oxymel", "honey-wine"].includes(String(id))
        ? "drinks"
        : "gifts";
